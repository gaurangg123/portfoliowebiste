#!/usr/bin/env node
// DataForge build: generates the static site from src/. Run from anywhere:
//   node tools/build.js
// No dependencies. Output is committed at the repository root, which GitHub Pages
// serves as-is (branch deploy, with .nojekyll so nothing is reprocessed):
//   index.html · work/<slug>/index.html · work/index.html · 404.html
//   assets/css/dataforge.css · assets/js/dataforge.js · sitemap.xml · robots.txt
'use strict';
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT = path.resolve(__dirname, '..');
const SRC = path.join(ROOT, 'src');
const site = require('../src/data/site.js');
const { PROJECTS, EXPERIMENT_TITLES } = require('../src/data/projects.js');
const domains = require('../src/data/domains.js');
const edu = require('../src/data/education.js');

const { head } = require('../src/components/head.js');
const { navigation, toTop } = require('../src/components/navigation.js');
const { footer } = require('../src/components/footer.js');
const { hero } = require('../src/components/hero.js');
const { about, ribbon } = require('../src/components/about.js');
const { expertise } = require('../src/components/expertise.js');
const { projects } = require('../src/components/projects.js');
const { experience } = require('../src/components/experience.js');
const { education } = require('../src/components/education.js');
const { architecture } = require('../src/components/architecture.js');
const { queryPage, queryPromo } = require('../src/components/query.js');
const queryData = require('../src/data/query.js');
const { contact } = require('../src/components/contact.js');
const { caseStudy, notFound } = require('../src/components/case-study.js');

/* ---------- walkthrough data: one source for the pages and the player ---------- */
global.window = {};
require(path.join(ROOT, 'assets/walkthroughs/demos.js'));
const DEMOS = global.window.PortfolioDemos;
delete global.window;
const CASES = PROJECTS.filter((p) => p.type === 'Company project');
for (const p of CASES) {
  const d = DEMOS[p.slug];
  if (!d) throw new Error(`${p.slug}: no walkthrough in demos.js`);
  if (d.duration % 1000) throw new Error(`${p.slug}: walkthrough duration must be whole seconds`);
}
const TITLES = { ...EXPERIMENT_TITLES };
for (const p of CASES) TITLES[p.slug] = DEMOS[p.slug].title;

/* ---------- bundles ---------- */
const STYLES = ['tokens', 'base', 'navigation', 'hero', 'about', 'stepper', 'expertise', 'projects', 'experience',
  'workflow', 'architecture', 'education', 'query', 'contact', 'footer', 'case-study', 'case-visuals', 'motion'];
const SCRIPTS = ['core', 'theme', 'nav', 'motion-pref', 'hero-lattice', 'clock', 'reveal', 'stepper', 'expertise',
  'projects', 'walkthrough-loader', 'explain', 'copy', 'papercut', 'legacy'];
// the Query the Engineer page loads its own small bundle on top of the shared one
const QUERY_SCRIPTS = ['query-engine', 'query-ui', 'net-field'];

const read = (f) => fs.readFileSync(f, 'utf8');
const hash = (s) => crypto.createHash('sha256').update(s).digest('hex').slice(0, 10);
const write = (rel, content) => {
  const f = path.join(ROOT, rel);
  fs.mkdirSync(path.dirname(f), { recursive: true });
  fs.writeFileSync(f, content);
  console.log('wrote', rel.padEnd(36), String(Buffer.byteLength(content)).padStart(7), 'bytes');
};

for (const n of STYLES) if (!fs.existsSync(path.join(SRC, 'styles', n + '.css'))) throw new Error(`missing src/styles/${n}.css`);
for (const n of SCRIPTS.concat(QUERY_SCRIPTS)) if (!fs.existsSync(path.join(SRC, 'scripts', n + '.js'))) throw new Error(`missing src/scripts/${n}.js`);

const css = `/* DataForge — generated by tools/build.js from src/styles/. Edit the sources, not this file. */\n` + STYLES
  .map((n) => `/* ===== ${n}.css ===== */\n` + read(path.join(SRC, 'styles', n + '.css')).replace(/\/\*[\s\S]*?\*\//g, '').replace(/[ \t]+$/gm, '').replace(/\n{2,}/g, '\n').trim())
  .join('\n') + '\n';
const js = `/* DataForge — generated by tools/build.js from src/scripts/. Edit the sources, not this file. */\n` + SCRIPTS
  .map((n) => `/* ===== ${n}.js ===== */\n` + read(path.join(SRC, 'scripts', n + '.js')).replace(/^\/\/ @ts-check\n/m, '').trim())
  .join('\n\n') + '\n';
const qjs = `/* DataForge — Query the Engineer bundle, generated by tools/build.js. */\n` + QUERY_SCRIPTS
  .map((n) => `/* ===== ${n}.js ===== */\n` + read(path.join(SRC, 'scripts', n + '.js')).replace(/^\/\/ @ts-check\n/m, '').trim())
  .join('\n\n') + '\n';
const v = { css: hash(css), js: hash(js), q: hash(qjs) };
const KB = queryData(TITLES);

/* ---------- homepage ---------- */
const SITE = site.siteUrl;
const personLd = {
  '@context': 'https://schema.org',
  '@graph': [
    {
      '@type': 'Person', '@id': `${SITE}#person`, name: site.name, jobTitle: site.role, url: SITE, email: `mailto:${site.email}`,
      image: `${SITE}assets/profile/gaurang.jpg`,
      address: { '@type': 'PostalAddress', addressLocality: 'Pune', addressCountry: 'IN' },
      worksFor: { '@type': 'Organization', name: site.company },
      alumniOf: { '@type': 'CollegeOrUniversity', name: 'SRM Institute of Science and Technology' },
      hasCredential: edu.certifications.map((c) => ({ '@type': 'EducationalOccupationalCredential', name: c.title })),
      knowsAbout: domains.map((d) => d.name),
      sameAs: [site.linkedin, site.github],
    },
    { '@type': 'WebSite', '@id': `${SITE}#website`, url: SITE, name: `${site.brand} — ${site.name}`, inLanguage: 'en-IN', author: { '@id': `${SITE}#person` } },
  ],
};

const page = (h, bodyClass, inner) => `${h}
<body class="${bodyClass}">
${inner}
</body>
</html>
`;

const home = page(head({
  base: '', v, legacy: true,
  title: `${site.name} — ${site.headline} | ${site.brand}`,
  description: `${site.name} is a ${site.headline} in Pune building data pipelines, AI applications and automated workflows at ${site.company}. Projects, experience and an interactive data architecture.`,
  url: SITE,
  ogTitle: `${site.name} — ${site.brand} · ${site.tagline}`,
  ogDescription: site.intro,
  jsonld: personLd,
}), 'page-home', `${navigation({ page: 'home', base: '' })}

<main id="main">
<span class="spine" data-spine aria-hidden="true"><i></i></span>
${hero()}

${ribbon()}

${about()}

${expertise()}

${projects(TITLES)}

${experience()}

${education()}

${architecture()}

${queryPromo({ kb: KB })}

${contact()}
</main>

${footer({ home: true, base: '' })}
${toTop()}

<!-- Papercut (instrumental): silent until someone presses Play; the file isn't requested before that. -->
<audio id="papercut" data-src="assets/audio/papercut-instrumental.mp3?v=2" preload="none"></audio>`);
write('index.html', home);

/* ---------- case studies ---------- */
CASES.forEach((p0, i) => {
  const p = { ...p0, title: TITLES[p0.slug] };
  const card = (q) => q && { ...q, title: TITLES[q.slug] };
  const base = '../../';
  const url = `${SITE}work/${p.slug}/`;
  const ld = {
    '@context': 'https://schema.org',
    '@graph': [
      { '@type': 'CreativeWork', name: p.title, headline: p.title, description: p.description, url, image: `${SITE}assets/projects/${p.slug}-1600.webp`, author: { '@type': 'Person', name: site.name, url: SITE }, isPartOf: { '@type': 'WebSite', '@id': `${SITE}#website` } },
      { '@type': 'BreadcrumbList', itemListElement: [
        { '@type': 'ListItem', position: 1, name: 'Home', item: SITE },
        { '@type': 'ListItem', position: 2, name: 'Projects', item: `${SITE}#projects` },
        { '@type': 'ListItem', position: 3, name: p.title, item: url },
      ] },
    ],
  };
  write(`work/${p.slug}/index.html`, page(head({
    base, v, url, ogType: 'article',
    title: `${p.title} — ${site.name} | ${site.brand}`,
    description: p.description,
    ogTitle: `${p.title} — ${site.name}`,
    ogDescription: p.lede,
    jsonld: ld,
  }), 'page-case', `${navigation({ page: 'case', base })}

${caseStudy({ p, demo: DEMOS[p.slug], prev: card(CASES[i - 1]), next: card(CASES[i + 1]), all: PROJECTS })}

${footer({ home: false, base })}
${toTop()}`));
});

/* ---------- Query the Engineer: its own page, a folder GitHub Pages serves directly ---------- */
{
  const base = '../';
  const url = `${SITE}${site.queryPath}`;
  write(`${site.queryPath}index.html`, page(head({
    base, v, url,
    title: `Query the Engineer — ${site.name} | ${site.brand}`,
    description: `Ask about ${site.name}'s experience, projects, technologies and approach. A local portfolio assistant that answers from this portfolio's content, not an AI model.`,
    ogTitle: `Query the Engineer — ${site.name}`,
    ogDescription: 'Curious about what I build, how I think, or the technologies I work with? Explore my engineering profile through an interactive workspace.',
    extra: `<script src="${base}assets/js/query.js?v=${v.q}" defer></script>\n<script type="application/json" id="qe-kb">${JSON.stringify(KB).replace(/</g, '\\u003c')}</script>\n`,
  }), 'page-query', `${navigation({ page: 'query', base })}

${queryPage({ kb: KB, base })}

${footer({ home: false, base })}
${toTop()}`));
}

/* ---------- /work/ → the projects section ---------- */
write('work/index.html', `<!DOCTYPE html>
<html lang="en-IN">
<head>
<meta charset="utf-8" />
<title>Projects — ${site.name}</title>
<meta name="robots" content="noindex" />
<meta http-equiv="refresh" content="0; url=../#projects" />
<link rel="canonical" href="${SITE}#projects" />
</head>
<body>
<p><a href="../#projects">See all projects on the homepage</a></p>
</body>
</html>
`);

/* ---------- 404: served at any depth, so every URL is absolute ---------- */
write('404.html', page(head({
  base: site.basePath, v, robots: 'noindex',
  title: `Page not found — ${site.name}`,
  description: 'This page doesn’t exist.',
}), 'page-404', `${navigation({ page: '404', base: site.basePath })}

${notFound()}

${footer({ home: false, base: site.basePath })}`));

/* ---------- bundles, sitemap, robots ---------- */
write('assets/css/dataforge.css', css);
write('assets/js/dataforge.js', js);
write('assets/js/query.js', qjs);
write('sitemap.xml', `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
  <url><loc>${SITE}</loc><priority>1.0</priority></url>
  <url><loc>${SITE}${site.queryPath}</loc><priority>0.7</priority></url>
${CASES.map((p) => `  <url><loc>${SITE}work/${p.slug}/</loc><priority>0.8</priority></url>`).join('\n')}
</urlset>
`);
write('robots.txt', `# GitHub Pages serves this site under /portfoliowebiste/. Crawlers read robots.txt only
# at a host's root, so this file documents intent; submit the sitemap in Search Console.
User-agent: *
Allow: /

Sitemap: ${SITE}sitemap.xml
`);
if (!fs.existsSync(path.join(ROOT, '.nojekyll'))) write('.nojekyll', '');
